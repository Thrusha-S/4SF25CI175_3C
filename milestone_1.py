df.isnull().sum()

df[['PM2.5', 'PM10', 'NOx', 'AQI_Score']].head()

def category(aqi):
    if aqi < 50:
        return "Good"
    elif aqi < 100:
        return "Moderate"
    else:
        return "Poor"

df['Air_Quality'] = df['AQI_Score'].apply(category)

df[['AQI_Score', 'Air_Quality']].head()

df['Air_Quality'].value_counts()

df[['PM2.5', 'PM10', 'NOx', 'NO2', 'SO2']].mean()

